"""Sketch-augmented datasets for AG-Diff.

Two dataset classes are provided:

1.  SketchJointDataset (Stage 1 – AlignNet training)
    Returns pairs of (sketch_image, joint_features) for contrastive alignment.
    One sample = one frame of one motion clip.

2.  SketchMotionDataset (Stage 2 – AG-Diff diffusion training)
    Wraps Text2MotionDatasetV2; additionally loads a sketch image for a
    randomly chosen keyframe index.  The sketch is passed through AlignNet
    (or returned raw if `precompute_latents=False`) and added to the batch.

─────────────────────────────────────────────────────────────────────────────
Dataset on disk – required layout
─────────────────────────────────────────────────────────────────────────────

    dataset/
    ├── HumanML3D/
    │   ├── new_joint_vecs/          ← raw HumanML3D .npy files  [T, 263]
    │   ├── new_joints/              ← (optional) XYZ .npy files [T, 22, 3]
    │   ├── texts/                   ← text annotation .txt files
    │   ├── train.txt / val.txt / test.txt
    │   └── Mean.npy / Std.npy       ← normalisation statistics  [263]
    └── sketches/                    ← PNG images generated by draw_sketches.py
        ├── {name}_{frame:04d}.png
        └── …

Sketch filename convention
    "{name}_{frame_index:04d}.png"
    e.g.  "000021_0042.png" = clip "000021", frame 42.

Joint-feature slice for AlignNet
    We use the first 67 dimensions (drop_redundant=True convention):
        [0]    root angular velocity  (ṙa)
        [1:3]  root linear velocity XZ (ṙxz)
        [3]    root height            (ṙh)
        [4:67] local joint positions  (jp, 21 joints × 3)
    For sketch-joint alignment the most informative part is jp (4:67).
    All 67 dims are passed to the JointEncoder for completeness.
"""

import os
import random
from typing import Optional, List, Tuple

import numpy as np
import torch
from torch.utils.data import Dataset
from PIL import Image
import torchvision.transforms as T

from data_loaders.humanml.data.dataset import Text2MotionDatasetV2
from data_loaders.humanml.utils.get_opt import get_opt


# ═══════════════════════════════════════════════════════════════════════════ #
#  1.  SketchJointDataset  (Stage 1 – AlignNet)                              #
# ═══════════════════════════════════════════════════════════════════════════ #

class SketchJointDataset(Dataset):
    """Per-frame paired (sketch image, joint features) dataset.

    Args:
        sketch_dir  : path to directory containing sketch PNGs
        motion_dir  : path to directory containing raw HumanML3D .npy files
        mean        : [263] global mean (from HumanML3D metadata)
        std         : [263] global std
        split_file  : path to train/val/test split .txt file
        img_size    : resize sketches to (img_size, img_size) pixels
        joint_dim   : how many leading feature dims to keep (67 = drop_redundant)
        max_frames  : optional cap on frames per clip (avoids very long clips)
    """

    def __init__(self,
                 sketch_dir: str,
                 motion_dir: str,
                 mean: np.ndarray,
                 std: np.ndarray,
                 split_file: str,
                 img_size: int = 256,
                 joint_dim: int = 67,
                 max_frames: int = 196):
        self.sketch_dir = sketch_dir
        self.motion_dir = motion_dir
        self.joint_dim = joint_dim
        self.mean = mean[:joint_dim].astype(np.float32)
        self.std = std[:joint_dim].astype(np.float32)
        self.std = np.where(self.std < 1e-8, 1.0, self.std)  # avoid div/0

        self.transform = T.Compose([
            T.Resize((img_size, img_size)),
            T.ToTensor(),               # → [1, H, W], values in [0, 1]
            T.Normalize([0.5], [0.5]),  # → values in [-1, 1]
        ])

        # Build index of (name, frame_idx, raw_joint_feature) triples
        self.samples: List[Tuple[str, int, np.ndarray]] = []
        names = self._read_split(split_file)
        for name in names:
            motion_path = os.path.join(motion_dir, name + '.npy')
            if not os.path.exists(motion_path):
                continue
            motion = np.load(motion_path).astype(np.float32)  # [T, 263]
            n_frames = min(len(motion), max_frames)
            for j in range(n_frames):
                sketch_path = os.path.join(sketch_dir, f'{name}_{j:04d}.png')
                if os.path.exists(sketch_path):
                    self.samples.append((name, j, motion[j, :joint_dim]))

        print(f'SketchJointDataset: {len(self.samples)} paired samples '
              f'(joint_dim={joint_dim})')

    @staticmethod
    def _read_split(split_file: str) -> List[str]:
        with open(split_file, 'r') as fh:
            return [line.strip() for line in fh if line.strip()]

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, torch.Tensor]:
        name, frame_idx, raw_joint = self.samples[idx]

        # Load and transform sketch image → [1, H, W]
        sketch_path = os.path.join(self.sketch_dir, f'{name}_{frame_idx:04d}.png')
        img = Image.open(sketch_path).convert('L')
        sketch = self.transform(img)

        # Z-normalise joint features
        joint = (raw_joint - self.mean) / self.std
        joint = torch.from_numpy(joint)

        return sketch, joint  # ([1,H,W], [joint_dim])


# ═══════════════════════════════════════════════════════════════════════════ #
#  2.  SketchMotionDataset  (Stage 2 – AG-Diff diffusion)                    #
# ═══════════════════════════════════════════════════════════════════════════ #

class SketchMotionDataset(Text2MotionDatasetV2):
    """Text2MotionDatasetV2 extended with sketch guidance for AG-Diff training.

    For each motion sequence, one keyframe is selected at random and the
    corresponding sketch is loaded.  The sketch image (or precomputed latent)
    is returned alongside the standard motion/text data.

    Additional returned fields (appended to the tuple):
        sketch  : torch.Tensor  [1, H, W]  – normalised sketch image
                  (or None if no sketch exists for the selected keyframe)
        sketch_keyframe_idx : int  – 0-based frame index within the padded sequence

    Args:
        sketch_dir       : path to sketch PNG directory
        img_size         : sketch image resolution
        n_sketch_frames  : number of sketch keyframes to sample per clip
                           (currently only 1 is supported during training)
        sketch_drop_prob : probability of randomly masking sketch (to train
                           the model to work without sketch, i.e. CFG-style)
        All other kwargs forwarded to Text2MotionDatasetV2.
    """

    def __init__(self,
                 *args,
                 sketch_dir: str,
                 img_size: int = 256,
                 n_sketch_frames: int = 1,
                 sketch_drop_prob: float = 0.1,
                 **kwargs):
        super().__init__(*args, **kwargs)
        self.sketch_dir = sketch_dir
        self.n_sketch_frames = n_sketch_frames
        self.sketch_drop_prob = sketch_drop_prob

        self.sketch_transform = T.Compose([
            T.Resize((img_size, img_size)),
            T.ToTensor(),
            T.Normalize([0.5], [0.5]),
        ])

    # ── override __getitem__ ──────────────────────────────────────────────── #

    def __getitem__(self, item: int):
        # Standard fields from parent
        result = super().__getitem__(item)
        # result = (word_emb, pos_oh, caption, sent_len, motion, m_length, tokens)
        word_emb, pos_oh, caption, sent_len, motion, m_length, tokens = result

        # motion shape after parent: [max_motion_length, joint_dim]
        # Select a random keyframe within the valid motion length
        sketch = None
        kf_idx = 0
        if m_length > 0 and not (self.training and random.random() < self.sketch_drop_prob):
            kf_idx = random.randint(0, m_length - 1)
            # Recover original clip name from name_list
            idx = self.pointer + item
            name = self.name_list[idx]
            # Strip any leading letter prefix added for sub-clips (e.g. "A_000021")
            base_name = name.split('_', 1)[-1] if '_' in name else name
            sketch_path = os.path.join(self.sketch_dir, f'{base_name}_{kf_idx:04d}.png')
            if os.path.exists(sketch_path):
                img = Image.open(sketch_path).convert('L')
                sketch = self.sketch_transform(img)  # [1, H, W]

        if sketch is None:
            # Return a zero-sketch tensor as placeholder; training loop will mask it
            sketch = torch.zeros(1, 256, 256)

        return word_emb, pos_oh, caption, sent_len, motion, m_length, tokens, sketch, kf_idx

    # Keep training/eval mode flag so sketch_drop_prob works correctly
    @property
    def training(self) -> bool:
        return self.mode == 'train'


# ═══════════════════════════════════════════════════════════════════════════ #
#  3.  Collate function for SketchMotionDataset                              #
# ═══════════════════════════════════════════════════════════════════════════ #

def sketch_t2m_collate(batch):
    """Collate function for SketchMotionDataset.

    Extends the standard `t2m_collate` with sketch tensors and keyframe indices.
    """
    from data_loaders.tensors import collate as base_collate

    adapted = []
    sketch_list = []
    kf_idx_list = []
    for b in batch:
        word_emb, pos_oh, caption, sent_len, motion, m_length, tokens, sketch, kf_idx = b
        adapted.append({
            'inp': torch.tensor(motion.T).float().unsqueeze(1),  # [J, 1, T]
            'text': caption,
            'tokens': tokens,
            'lengths': m_length,
        })
        sketch_list.append(sketch)          # [1, H, W]
        kf_idx_list.append(kf_idx)

    motion_batch, cond = base_collate(adapted)

    # Stack sketch images: [bs, 1, H, W]
    cond['y']['sketch'] = torch.stack(sketch_list, dim=0)
    # Keyframe indices: [bs]
    cond['y']['sketch_keyframe_idx'] = torch.tensor(kf_idx_list, dtype=torch.long)

    return motion_batch, cond


# ═══════════════════════════════════════════════════════════════════════════ #
#  4.  Factory helper                                                         #
# ═══════════════════════════════════════════════════════════════════════════ #

def get_sketch_dataset(dataset_root: str,
                       sketch_dir: str,
                       split: str = 'train',
                       num_frames: int = 196,
                       drop_redundant: bool = True,
                       img_size: int = 256,
                       sketch_drop_prob: float = 0.1) -> SketchMotionDataset:
    """Convenience factory that wires up HumanML3D paths and returns a
    SketchMotionDataset ready for use in AG-Diff training.

    Args:
        dataset_root  : path to the HumanML3D root dir (contains Mean.npy etc.)
        sketch_dir    : path to the generated sketch PNG directory
        split         : 'train' | 'val' | 'test'
        …
    """
    opt = get_opt(os.path.join(dataset_root, 'opt.txt'), device='cpu')
    opt.max_motion_length = num_frames

    mean = np.load(os.path.join(dataset_root, 'Mean.npy'))
    std = np.load(os.path.join(dataset_root, 'Std.npy'))

    split_file = os.path.join(dataset_root, f'{split}.txt')

    from data_loaders.humanml.utils.word_vectorizer import WordVectorizer
    w_vectorizer = WordVectorizer(
        os.path.join(dataset_root, 'glove'), 'our_vab'
    )

    return SketchMotionDataset(
        opt, mean, std, split_file, w_vectorizer,
        mode=split,
        drop_redundant=drop_redundant,
        sketch_dir=sketch_dir,
        img_size=img_size,
        sketch_drop_prob=sketch_drop_prob,
    )
